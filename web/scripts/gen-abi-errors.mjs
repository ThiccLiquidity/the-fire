// Writes src/lib/abiErrors.generated.ts: every custom error in the card ABIs (src/lib/abi/*.json) and src/lib/extraErrors.json, with its inputs
// and the contracts that can raise it. src/lib/errors.ts gives each one a plain-English message, keyed by this list,
// so after the ABIs are regenerated: run `npm run gen:errors`, then `npx tsc -b` names any error still missing a
// message (or a message for an error that no longer exists).
//
//   node scripts/gen-abi-errors.mjs          write the file
//   node scripts/gen-abi-errors.mjs --check  exit 1 if the file is out of date (for CI)

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const abiDir = join(web, "src/lib/abi");
const out = join(web, "src/lib/abiErrors.generated.ts");

// the card ABIs, then src/lib/extraErrors.json: errors from contracts outside them (the randomness router and adapter,
// OpenZeppelin's ERC-20 errors), as { contract: [error fragments] }
const extraFile = join(web, "src/lib/extraErrors.json");
const sources = [
  ...readdirSync(abiDir).filter((f) => f.endsWith(".json")).sort()
    .map((file) => [file.replace(/Abi\.json$/, ""), JSON.parse(readFileSync(join(abiDir, file), "utf8"))]),
  ...Object.entries(JSON.parse(readFileSync(extraFile, "utf8"))).filter(([k, v]) => !k.startsWith("_") && Array.isArray(v)),
];

const byName = new Map();
for (const [contract, abi] of sources) {
  for (const item of abi) {
    if (item.type !== "error") continue;
    const inputs = item.inputs.map((i) => ({ name: i.name, type: i.type }));
    const sig = `${item.name}(${inputs.map((i) => i.type).join(",")})`;
    const seen = byName.get(item.name);
    if (seen && seen.sig !== sig) throw new Error(`Two errors named ${item.name} with different inputs: ${seen.sig}, ${sig}`);
    if (seen) seen.contracts.push(contract);
    else byName.set(item.name, { sig, inputs, contracts: [contract] });
  }
}

const names = [...byName.keys()].sort();
const q = JSON.stringify;
const text = `// GENERATED by scripts/gen-abi-errors.mjs from src/lib/abi/*.json and src/lib/extraErrors.json. Do not edit: run \`npm run gen:errors\`.

/** Every custom error the site can meet (the card ABIs, the randomness contracts, ERC-20): its inputs and the contracts that can raise it. */
export const ABI_ERRORS = {
${names.map((n) => { const e = byName.get(n); return `  ${n}: { inputs: [${e.inputs.map((i) => `{ name: ${q(i.name)}, type: ${q(i.type)} }`).join(", ")}], contracts: [${e.contracts.map(q).join(", ")}] },`; }).join("\n")}
} as const;

export type AbiErrorName = keyof typeof ABI_ERRORS;

/** The same errors as ABI fragments, for decoding raw revert data. */
export const ERRORS_ABI = (Object.keys(ABI_ERRORS) as AbiErrorName[]).map((name) => ({
  type: "error" as const, name, inputs: ABI_ERRORS[name].inputs,
}));
`;

if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(out, "utf8"); } catch { /* missing */ }
  if (cur !== text) { console.error("src/lib/abiErrors.generated.ts is out of date: run npm run gen:errors"); process.exit(1); }
  console.log(`abiErrors.generated.ts is up to date (${names.length} errors)`);
} else {
  writeFileSync(out, text);
  console.log(`Wrote src/lib/abiErrors.generated.ts: ${names.length} errors`);
}
