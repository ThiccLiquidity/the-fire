// Writes abis/*.ts (the events and reads the indexer uses) from the contracts' build (contracts/out). Run after a
// contract change: node abis/gen.mjs (from ops/indexer; needs `forge build` first).
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
for (const c of ['FireCards', 'FirePacks', 'FirePsa', 'FireSale', 'FireCredits']) {
  const abi = JSON.parse(readFileSync(new URL(`../../../contracts/out/${c}.sol/${c}.json`, here), 'utf8')).abi.filter((x) => x.type === 'event');
  writeFileSync(new URL(`${c}.ts`, here), `// generated by abis/gen.mjs from contracts/out: do not edit\nexport const ${c}Abi = ${JSON.stringify(abi, null, 1)} as const;\n`);
  console.log(c, abi.length, 'events');
}
